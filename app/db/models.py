import enum
from datetime import datetime
from sqlalchemy import Index, DateTime, Enum, ForeignKey, Integer, String, Text, func
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.session import Base
from app.schemas import ScanMode, FindingStatus, SeverityLevel


class Repository(Base):
    __tablename__ = "repositories"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    target_path: Mapped[str] = mapped_column(String(512), nullable=False)
    repo_name: Mapped[str | None] = mapped_column(String(256), nullable=True, index=True)  # owner/repo
    size_kb: Mapped[int | None] = mapped_column(Integer, nullable=True)
    stars: Mapped[int | None] = mapped_column(Integer, nullable=True)
    status: Mapped[str | None] = mapped_column(String(32), default="completed", nullable=True)
    scan_mode: Mapped[ScanMode] = mapped_column(
        Enum(ScanMode), default=ScanMode.MANUAL, nullable=False
    )
    scanned_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    # 1-to-many relationship: deleting a repo record deletes its findings
    vulnerabilities: Mapped[list["Vulnerability"]] = relationship(
        "Vulnerability", back_populates="repository", cascade="all, delete-orphan"
    )


class Vulnerability(Base):
    __tablename__ = "vulnerabilities"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    repository_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("repositories.id", ondelete="CASCADE"), nullable=False
    )

    file_path: Mapped[str] = mapped_column(String(512), nullable=False)
    line_number: Mapped[int] = mapped_column(Integer, nullable=False)
    vulnerability_type: Mapped[str] = mapped_column(String(128), nullable=False)  # e.g., "SQL Injection"
    severity: Mapped[SeverityLevel] = mapped_column(
        Enum(SeverityLevel), default=SeverityLevel.MEDIUM, nullable=False
    )
    
    # Detailed technical reports generated by the LLM
    description: Mapped[str] = mapped_column(Text, nullable=False)
    remediation: Mapped[str | None] = mapped_column(Text, nullable=True)
    code_snippet: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Trust metadata: how sure the engine is, who found it, and how it was verified
    confidence: Mapped[int | None] = mapped_column(Integer, nullable=True)
    source: Mapped[str | None] = mapped_column(String(32), nullable=True)  # ast|bandit|secret|semgrep|dependency|history
    verification_note: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Lifecycle & Publication Tracking
    status: Mapped[FindingStatus] = mapped_column(
        Enum(FindingStatus), default=FindingStatus.PENDING_REVIEW, nullable=False
    )
    github_issue_url: Mapped[str | None] = mapped_column(String(512), nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    # Back reference to parent repository
    repository: Mapped["Repository"] = relationship(
        "Repository", back_populates="vulnerabilities"
    )

class ScanRun(Base):
    """Persisted execution state; independent of a browser session or repository record."""
    __tablename__ = "scan_runs"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    mode: Mapped[str] = mapped_column(String(16), nullable=False)
    target: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(String(32), default="running", nullable=False, index=True)
    stage: Mapped[str] = mapped_column(String(64), default="Preparing", nullable=False)
    current_repo: Mapped[str | None] = mapped_column(Text, nullable=True)
    repository_id: Mapped[int | None] = mapped_column(Integer, nullable=True)
    current_file: Mapped[str | None] = mapped_column(Text, nullable=True)
    progress: Mapped[int | None] = mapped_column(Integer, nullable=True)
    total: Mapped[int | None] = mapped_column(Integer, nullable=True)
    message: Mapped[str | None] = mapped_column(Text, nullable=True)
    worker_pid: Mapped[int] = mapped_column(Integer, nullable=False)
    worker_host: Mapped[str] = mapped_column(String(256), nullable=False)
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)


# Explicit order/filter indexes also used by the idempotent existing-schema upgrade.
PERFORMANCE_INDEXES = (
    Index("ix_vulnerabilities_repository_id_id", Vulnerability.repository_id, Vulnerability.id),
    Index("ix_vulnerabilities_status_id", Vulnerability.status, Vulnerability.id),
    Index("ix_vulnerabilities_repository_id_status_id", Vulnerability.repository_id, Vulnerability.status, Vulnerability.id),
    Index("ix_repositories_scanned_at_id", Repository.scanned_at.desc(), Repository.id.desc()),
    Index("ix_repositories_lower_repo_name_scanned_at", func.lower(Repository.repo_name), Repository.scanned_at.desc()),
    Index("ix_scan_runs_started_at_id", ScanRun.started_at.desc(), ScanRun.id.desc()),
    Index("ix_scan_runs_status_started_at_id", ScanRun.status, ScanRun.started_at.desc(), ScanRun.id.desc()),
    Index("ix_vulnerabilities_report_url_id", Vulnerability.github_issue_url, Vulnerability.id.desc(),
          postgresql_where=Vulnerability.github_issue_url.isnot(None) & (Vulnerability.github_issue_url != ""),
          sqlite_where=Vulnerability.github_issue_url.isnot(None) & (Vulnerability.github_issue_url != "")),
)
